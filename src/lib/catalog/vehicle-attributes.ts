const hasHangul = (value: string) => /[\uac00-\ud7af]/u.test(value);

export function exteriorColorLabel(value: string | null | undefined) {
  if (!value?.trim()) return "Не указан";
  const normalized = [...EXTERIOR_COLOR_LABELS].sort(([left], [right]) => right.length - left.length).reduce(
    (result, [source, target]) => result.replaceAll(source, target),
    value.trim(),
  ).replace(/\s{2,}/gu, " ").trim();
  return normalized && !hasHangul(normalized) ? normalized : "Не указан";
}

/** Returns a normalized source token only for unambiguous drivetrain marks. */
export function inferDriveType(...values: Array<string | null | undefined>) {
  const source = values.filter(Boolean).join(" ").toUpperCase();
  if (/\b(?:AWD|4WD)\b|4륜|\bXDRIVE(?=\d|\b)|4\s*MATIC|\bQUATTRO\b|4\s*MOTION|\bHTRAC\b|SH-AWD/u.test(source)) return "4WD";
  if (/\bFWD\b|전륜/u.test(source)) return "FWD";
  if (/\bRWD\b|후륜/u.test(source)) return "RWD";
  if (/\b2WD\b|2륜/u.test(source)) return "2WD";
  return null;
}

export function driveLabel(value: string | null | undefined, trim?: string | null) {
  const inferred = inferDriveType(value, trim);
  if (inferred === "4WD") return "Полный";
  if (inferred === "FWD") return "Передний";
  if (inferred === "RWD") return "Задний";
  if (inferred === "2WD") return "2WD";
  if (!value) return "Не указан";
  const normalized = value.replace("구동", "привод");
  return hasHangul(normalized) ? "Не указан" : normalized;
}
